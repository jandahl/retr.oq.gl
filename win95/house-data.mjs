export function overlapRatio(hit, target) {
  const width = Math.max(0, Math.min(hit.x + hit.w, target.x + target.w) - Math.max(hit.x, target.x));
  const height = Math.max(0, Math.min(hit.y + hit.h, target.y + target.h) - Math.max(hit.y, target.y));
  const area = hit.w * hit.h;
  if (area <= 0) return 0;
  return (width * height) / area;
}

