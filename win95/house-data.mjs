export const catalogs = { en, da };

export function t(locale, key, vars) {
  let raw = catalogs[locale][key];
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name) => (vars[name] != null ? String(vars[name]) : match));
}

const TOUR = ["tour.0", "tour.1", "tour.2", "tour.3"];

export function tourLines(locale) {
  return TOUR.map((key) => t(locale, key));
}

/** Four choices when the pool allows it. `random` is injectable for tests. */
export function pickQuestion(entries, random = Math.random) {
  const pool = [];
  const seenGloss = new Set();
  for (const entry of entries) {
    const lexeme = String(entry.lexeme || "").trim();
    const gloss = String(entry.gloss_en || "").trim();
    if (lexeme.length < 2 || gloss.length <= 3) continue;
    const key = gloss.toLowerCase();
    if (seenGloss.has(key)) continue;
    seenGloss.add(key);
    pool.push({ lexeme, gloss });
  }
  if (pool.length < 4) return null;
  const bag = pool.slice();
  for (let i = bag.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    const swap = bag[i];
    bag[i] = bag[j];
    bag[j] = swap;
  }
  const answer = bag[0];
  const choices = bag.slice(0, 4);
  for (let i = choices.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    const swap = choices[i];
    choices[i] = choices[j];
    choices[j] = swap;
  }
  return { gloss: answer.gloss, answer: answer.lexeme, choices: choices.map((c) => c.lexeme) };
}
