#!/usr/bin/env python3
"""Repack the locally downloaded Redneck shareware archive for js-dos."""

from __future__ import annotations

import argparse
import io
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("archive", type=Path, help="locally obtained demo ZIP")
    parser.add_argument("output", type=Path, help="output .jsdos bundle")
    parser.add_argument(
        "--config",
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / "vendor/redneck/game-data/redneck-demo.cfg",
        help="preconfigured REDNECK.CFG generated by the demo setup utility",
    )
    args = parser.parse_args()
    if not args.config.is_file():
        raise SystemExit(f"Missing Redneck setup config: {args.config}")

    with ZipFile(args.archive) as source:
        names = {name.casefold(): name for name in source.namelist()}
        demo_exe = next(
            (name for name in names if name.endswith("/demo/redneck.exe")), None
        )
        if demo_exe is None:
            raise SystemExit("Archive does not contain the expected DEMO/REDNECK.EXE")
        archive_root = names[demo_exe][: -len("demo/redneck.exe")]
        dosbox_config = """[sdl]
output=surface

[dosbox]
machine=svga_s3
memsize=32

[cpu]
core=normal
cycles=30000

[mixer]
rate=44100

[sblaster]
sbtype=sb16

[autoexec]
mount c .
c:
cd DEMO
redneck.exe
"""
        output = io.BytesIO()
        with ZipFile(output, "w", ZIP_DEFLATED) as bundle:
            bundle.writestr(".jsdos/dosbox.conf", dosbox_config)
            for name in source.namelist():
                if not name.startswith(archive_root) or name.endswith("/"):
                    continue
                relative = name[len(archive_root) :]
                if not relative:
                    continue
                bundle.writestr(relative, source.read(name))
            bundle.writestr("DEMO/REDNECK.CFG", args.config.read_bytes())

        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(output.getvalue())


if __name__ == "__main__":
    main()
