#!/usr/bin/env python3
"""Repack the locally downloaded Duke Nukem 3D shareware archive for js-dos."""

from __future__ import annotations

import argparse
import io
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("archive", type=Path, help="locally obtained demo/shareware ZIP")
    parser.add_argument("output", type=Path, help="output .jsdos bundle")
    parser.add_argument(
        "--config",
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / "vendor/duke3d/game-data/duke3d.cfg",
        help="preconfigured DUKE3D.CFG generated by the setup utility",
    )
    args = parser.parse_args()

    with ZipFile(args.archive) as source:
        names = {name.casefold(): name for name in source.namelist()}
        duke_exe = next(
            (name for name in names if name.endswith("duke3d.exe")), None
        )
        if duke_exe is None:
            raise SystemExit("Archive does not contain DUKE3D.EXE")

        duke_actual = names[duke_exe]
        archive_root = duke_actual[: -len("duke3d.exe")]

        dosbox_config = """[sdl]
output=surface

[dosbox]
machine=svga_s3
memsize=32

[cpu]
core=normal
cycles=30000

[mixer]
rate=44100

[sblaster]
sbtype=sb16
sbbase=220
irq=7
dma=1
hdma=5
sbmixer=true
oplmode=auto
oplemu=default
oplrate=44100

[autoexec]
mount c .
c:
duke3d.exe
"""
        output = io.BytesIO()
        with ZipFile(output, "w", ZIP_DEFLATED) as bundle:
            bundle.writestr(".jsdos/dosbox.conf", dosbox_config)
            for name in source.namelist():
                if not name.startswith(archive_root) or name.endswith("/"):
                    continue
                relative = name[len(archive_root) :]
                if not relative:
                    continue
                # Skip unnecessary extras or nested docs
                if relative.upper().startswith("EXTRAS/") or relative.upper().endswith(".ICO") or relative.upper().endswith(".ZIP") or relative.upper() == "DUKE3D.CFG":
                    continue
                bundle.writestr(relative, source.read(name))

            if args.config.is_file():
                bundle.writestr("DUKE3D.CFG", args.config.read_bytes())

        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(output.getvalue())
        print(f"Repacked {args.output} ({len(output.getvalue())} bytes)")


if __name__ == "__main__":
    main()
